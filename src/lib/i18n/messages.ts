export const MESSAGES: Record<Locale, Catalogue> = { 'en-GB': en, 'it-IT': it, 'es-ES': es, 'de-DE': de };

/** Look up a message and fill {placeholders}. Missing placeholders are left visible so they are caught in tests. */
export function translate(
  locale: Locale,
  key: MessageKey,
  vars: Record<string, string | number> = {},
): string {
  const template = MESSAGES[locale][key];
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
